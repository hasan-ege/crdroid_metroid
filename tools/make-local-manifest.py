#!/usr/bin/env python3
"""Turns fuad00's LineageOS 23.2 metroid local manifest into one for crDroid 16.0.

Projects that crDroid replaces with its own forks (see metroid-patches.py) are left to
crDroid; their metroid commits are cherry-picked by apply-metroid-patches.sh instead.
Everything else (device tree, qcom-caf sm8750 HALs, ...) comes straight from fuad00.

    make-local-manifest.py <fuad00 metroid.xml> > .repo/local_manifests/metroid.xml
"""
import re
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, __import__("os").path.dirname(__file__))
from importlib import import_module

CRDROID_OWNED = {path for _, _, path in import_module("metroid-patches").REPOS}


def main():
    # fuad00's header comment contains "--", which XML forbids inside comments; drop comments.
    text = re.sub(r"<!--.*?-->", "", open(sys.argv[1]).read(), flags=re.S)
    src = ET.fromstring(text)
    out = ET.Element("manifest")
    out.text = "\n  "
    out.append(ET.Comment(" Generated by tools/make-local-manifest.py from fuad00's metroid.xml "))
    for el in src:
        if el.tag == "remote":
            out.append(el)
        elif el.tag in ("remove-project", "project"):
            if el.get("path") in CRDROID_OWNED:
                continue
            if el.tag == "remove-project":
                el.set("optional", "true")  # not every LineageOS project is in crDroid's manifest
            out.append(el)
    for el in out:
        el.tail = "\n  "
    out[-1].tail = "\n"
    ET.ElementTree(out).write(sys.stdout, encoding="unicode", xml_declaration=True)
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
